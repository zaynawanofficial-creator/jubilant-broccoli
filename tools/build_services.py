"""Applies tools/services_new.py to SERVICE_CATALOG.csv and writes the plugin's data/group-content-extra.php.
Run: python3 tools/build_services.py (idempotent)."""
import csv, os, re
from services_new import NEW, EXTRA_ROWS, CANVA_SKU

ROOT = os.path.join(os.path.dirname(__file__), '..')
FEATURED = {'website-migration': 2, 'ecommerce-seo': 2, 'ppc-management': 2, 'tiktok-ads': 2}


def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower().replace('&', 'and')).strip('-')


def php(v, ind=1):
    t = '\t' * ind
    if isinstance(v, dict):
        return 'array(\n' + ''.join(f"{t}\t{php(k)} => {php(x, ind + 1)},\n" for k, x in v.items()) + f'{t})'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return "'" + str(v).replace('\\', '\\\\').replace("'", "\\'") + "'"


# ---- catalogue
path = os.path.join(ROOT, 'SERVICE_CATALOG.csv')
rows = list(csv.DictReader(open(path)))
hdr = list(rows[0].keys())
new_services = {n['service'] for n in NEW}
rows = [r for r in rows if r['service'] not in new_services and r['package_code'] not in {e['code'] for e in EXTRA_ROWS}]
note = 'Created from GB keyword data (4 Nov 2026); price set by Claude in the budget band; owner may change in wp-admin.'
extra = {}
for n in NEW:
    g = slug(n['group'])
    by_sku = {}
    for i, (title, qty, unit, price, turn, rev, ideal, deliv) in enumerate(n['packages'], 1):
        code = f"{n['slug']}-{g}-{i}"
        rows.append(dict(category=n['family'], service=n['service'], group=n['group'], package_code=code, package_title=title, quantity=qty, unit=unit,
                         pricing_model='fixed', currency='USD', price=str(price), price_approved='YES', scope_approved='YES', publish='READY',
                         turnaround=turn, revisions=rev, notes=note))
        by_sku[code] = {'ideal_for': ideal, 'deliverables': deliv, **({'featured': True} if i - 1 == FEATURED.get(n['slug'], 1) else {})}
    extra[g] = {'intro': n['intro'], 'brief': n['brief'], 'deliverables': n['packages'][0][7], 'exclusions': n['exclusions'], 'requirements': n['requirements'], 'by_sku': by_sku}
for e in EXTRA_ROWS:
    rows.append(dict(category=e['category'], service=e['service'], group=e['group'], package_code=e['code'], package_title=e['title'], quantity=e['qty'], unit=e['unit'],
                     pricing_model='fixed', currency='USD', price=str(e['price']), price_approved='YES', scope_approved='YES', publish='READY',
                     turnaround=e['turn'], revisions=e['rev'], notes=e['note']))
extra['branding'] = {'by_sku': {CANVA_SKU[0]: {'ideal_for': CANVA_SKU[1], 'deliverables': CANVA_SKU[2]}}}
w = csv.DictWriter(open(path, 'w', newline=''), fieldnames=hdr)
w.writeheader()
w.writerows(rows)

out = os.path.join(ROOT, 'wp-content', 'plugins', 'seo-booster-core', 'data', 'group-content-extra.php')
with open(out, 'w') as f:
    f.write("<?php\n/**\n * Generated by tools/build_services.py from tools/services_new.py. Merged into group-content.php.\n *\n * @package SEOBoosterCore\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn " + php(extra, 0) + ";\n")
print(len(rows), 'catalogue rows;', len(NEW), 'new services;', sum(len(n['packages']) for n in NEW) + len(EXTRA_ROWS), 'new packages')
